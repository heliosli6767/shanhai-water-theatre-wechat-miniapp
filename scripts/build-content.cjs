'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { loadHome, loadStory } = require('../backend/content.cjs');

// Export the backend's validated API content into the mini-program package.
// This runs at build time; no Node.js server or VM runs inside WeChat.
const home = loadHome();
const stories = {};
for (const story of home.stories) stories[story.id] = loadStory(story.id);
const target = path.resolve(__dirname, '../miniprogram/data/content.js');
const source = '// Generated by npm run build from backend/content/. Do not edit.\n' +
  "'use strict';\nmodule.exports = " + JSON.stringify({ home, stories }, null, 2) + ';\n';
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, source);
console.log('已内置 ' + home.stats.storyCount + ' 个故事、' + home.stats.sceneCount + ' 幕：' + home.contentVersion);
